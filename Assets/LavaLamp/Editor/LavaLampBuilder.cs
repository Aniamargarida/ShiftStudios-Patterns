using System.Collections.Generic;
using UnityEditor;
using UnityEngine;
using UnityEngine.Rendering;

/// <summary>
/// Generates the lava lamp model (lathed base, glass and cap), its materials and the LavaLamp prefab.
/// Run it from Tools > Lava Lamp > Rebuild Prefab. Re-running overwrites the meshes and prefab,
/// but keeps existing materials so colour tweaks made in the Inspector survive.
/// </summary>
public static class LavaLampBuilder
{
    const string Root = "Assets/LavaLamp";
    const float GlassBottom = 0.14f;
    const float GlassTop = 0.42f;
    const int Segments = 40;

    [MenuItem("Tools/Lava Lamp/Rebuild Prefab")]
    public static void Build()
    {
        EnsureFolder("Meshes");
        EnsureFolder("Materials");

        // Outer glass radius over normalized glass height. Shared by the mesh and the animation script.
        var glassCurve = new AnimationCurve(new Keyframe(0f, 0.045f), new Keyframe(0.35f, 0.062f), new Keyframe(1f, 0.032f));

        // Profiles are (radius, height) in meters, from the bottom of the lamp.
        var baseProfile = new[]
        {
            new Vector2(0f, 0f), new Vector2(0.08f, 0f), new Vector2(0.08f, 0.01f), new Vector2(0.074f, 0.03f),
            new Vector2(0.061f, 0.08f), new Vector2(0.048f, 0.13f), new Vector2(0.047f, GlassBottom), new Vector2(0f, GlassBottom),
        };
        var glassProfile = new List<Vector2> { new Vector2(0f, GlassBottom) };
        for (int i = 0; i <= 24; i++)
        {
            float h = i / 24f;
            glassProfile.Add(new Vector2(glassCurve.Evaluate(h), Mathf.Lerp(GlassBottom, GlassTop, h)));
        }
        glassProfile.Add(new Vector2(0f, GlassTop));
        var capProfile = new[]
        {
            new Vector2(0f, 0.418f), new Vector2(0.035f, 0.418f), new Vector2(0.034f, 0.425f),
            new Vector2(0.024f, 0.465f), new Vector2(0.012f, 0.476f), new Vector2(0f, 0.478f),
        };

        Mesh baseMesh = SaveMesh(Lathe("LavaLampBase", baseProfile, 0f, GlassBottom));
        Mesh glassMesh = SaveMesh(Lathe("LavaLampGlass", glassProfile.ToArray(), GlassBottom, GlassTop));
        Mesh capMesh = SaveMesh(Lathe("LavaLampCap", capProfile, 0.418f, 0.478f));

        Material blobMat = LoadOrCreateMaterial("LavaBlob", "ShiftStudios/LavaBlob", m => m.enableInstancing = true);
        Material glassMat = LoadOrCreateMaterial("LavaGlass", "ShiftStudios/LavaGlass", null);
        Material metalMat = LoadOrCreateMaterial("LavaLampMetal", "Universal Render Pipeline/Lit", m =>
        {
            m.SetColor("_BaseColor", new Color(0.16f, 0.16f, 0.18f));
            m.SetFloat("_Metallic", 0.85f);
            m.SetFloat("_Smoothness", 0.65f);
        });

        // Hierarchy: Base, Wax (mesh generated by LavaLamp at runtime), Glass, Cap.
        var root = new GameObject("LavaLamp");
        AddPart("Base", root.transform, baseMesh, metalMat);
        GameObject wax = AddPart("Wax", root.transform, null, blobMat);
        AddPart("Glass", root.transform, glassMesh, glassMat);
        AddPart("Cap", root.transform, capMesh, metalMat);

        var lamp = root.AddComponent<LavaLamp>();
        var so = new SerializedObject(lamp);
        so.FindProperty("waxFilter").objectReferenceValue = wax.GetComponent<MeshFilter>();
        so.FindProperty("glassBottom").floatValue = GlassBottom;
        so.FindProperty("glassTop").floatValue = GlassTop;
        so.FindProperty("glassRadius").animationCurveValue = glassCurve;
        so.ApplyModifiedPropertiesWithoutUndo();

        // Bake one frame of wax so the lamp looks right in the editor; in Play mode it's replaced by the live mesh.
        var preview = new Mesh { name = "LavaWaxPreview" };
        lamp.BakeMesh(4f, preview);
        wax.GetComponent<MeshFilter>().sharedMesh = SaveMesh(preview);

        PrefabUtility.SaveAsPrefabAsset(root, Root + "/LavaLamp.prefab");
        Object.DestroyImmediate(root);
        AssetDatabase.SaveAssets();
        Debug.Log($"[LavaLampBuilder] Built {Root}/LavaLamp.prefab (vertices: base {baseMesh.vertexCount}, glass {glassMesh.vertexCount}, cap {capMesh.vertexCount}, wax preview {lamp.LastVertexCount})");
    }

    /// <summary>Spins a (radius, height) profile around the Y axis. Corners sharper than 35° stay hard.</summary>
    static Mesh Lathe(string name, Vector2[] profile, float uvBottom, float uvTop)
    {
        const float smoothAngle = 35f;
        var vertices = new List<Vector3>();
        var normals = new List<Vector3>();
        var uvs = new List<Vector2>();
        var triangles = new List<int>();

        int segmentCount = profile.Length - 1;
        var segmentNormals = new Vector2[segmentCount];
        for (int i = 0; i < segmentCount; i++)
        {
            Vector2 d = profile[i + 1] - profile[i];
            segmentNormals[i] = new Vector2(d.y, -d.x).normalized;
        }

        for (int i = 0; i < segmentCount; i++)
        {
            if ((profile[i + 1] - profile[i]).sqrMagnitude < 1e-12f) continue;

            Vector2 startNormal = segmentNormals[i], endNormal = segmentNormals[i];
            if (i > 0 && Vector2.Angle(segmentNormals[i - 1], segmentNormals[i]) < smoothAngle)
                startNormal = (segmentNormals[i - 1] + segmentNormals[i]).normalized;
            if (i < segmentCount - 1 && Vector2.Angle(segmentNormals[i], segmentNormals[i + 1]) < smoothAngle)
                endNormal = (segmentNormals[i] + segmentNormals[i + 1]).normalized;

            int first = vertices.Count;
            for (int row = 0; row < 2; row++)
            {
                Vector2 p = row == 0 ? profile[i] : profile[i + 1];
                Vector2 n = row == 0 ? startNormal : endNormal;
                for (int s = 0; s <= Segments; s++)
                {
                    float angle = s / (float)Segments * Mathf.PI * 2f;
                    float cos = Mathf.Cos(angle), sin = Mathf.Sin(angle);
                    vertices.Add(new Vector3(p.x * cos, p.y, p.x * sin));
                    normals.Add(new Vector3(n.x * cos, n.y, n.x * sin).normalized);
                    uvs.Add(new Vector2(s / (float)Segments, Mathf.InverseLerp(uvBottom, uvTop, p.y)));
                }
            }

            for (int s = 0; s < Segments; s++)
            {
                int a0 = first + s, a1 = a0 + 1, b0 = first + Segments + 1 + s, b1 = b0 + 1;
                AddTriangle(vertices, normals, triangles, a0, b0, a1);
                AddTriangle(vertices, normals, triangles, a1, b0, b1);
            }
        }

        var mesh = new Mesh { name = name };
        mesh.SetVertices(vertices);
        mesh.SetNormals(normals);
        mesh.SetUVs(0, uvs);
        mesh.SetTriangles(triangles, 0);
        mesh.RecalculateBounds();
        mesh.RecalculateTangents();
        return mesh;
    }

    /// <summary>Adds a triangle facing the same way as its vertex normals; skips degenerate ones on the axis.</summary>
    static void AddTriangle(List<Vector3> v, List<Vector3> n, List<int> triangles, int i0, int i1, int i2)
    {
        Vector3 faceNormal = Vector3.Cross(v[i1] - v[i0], v[i2] - v[i0]);
        if (faceNormal.sqrMagnitude < 1e-14f) return;
        bool facesOut = Vector3.Dot(faceNormal, n[i0] + n[i1] + n[i2]) >= 0f;
        triangles.Add(i0);
        triangles.Add(facesOut ? i1 : i2);
        triangles.Add(facesOut ? i2 : i1);
    }

    static Mesh SaveMesh(Mesh mesh)
    {
        string path = $"{Root}/Meshes/{mesh.name}.asset";
        var existing = AssetDatabase.LoadAssetAtPath<Mesh>(path);
        if (existing == null)
        {
            AssetDatabase.CreateAsset(mesh, path);
            return mesh;
        }
        // Overwrite in place so references (and the asset GUID) stay valid.
        EditorUtility.CopySerialized(mesh, existing);
        Object.DestroyImmediate(mesh);
        return existing;
    }

    static Material LoadOrCreateMaterial(string name, string shaderName, System.Action<Material> setup)
    {
        string path = $"{Root}/Materials/{name}.mat";
        var existing = AssetDatabase.LoadAssetAtPath<Material>(path);
        if (existing != null) return existing;
        var mat = new Material(Shader.Find(shaderName)) { name = name };
        setup?.Invoke(mat);
        AssetDatabase.CreateAsset(mat, path);
        return mat;
    }

    static GameObject AddPart(string name, Transform parent, Mesh mesh, Material material)
    {
        var go = new GameObject(name);
        go.transform.SetParent(parent, false);
        go.AddComponent<MeshFilter>().sharedMesh = mesh;
        SetupRenderer(go.AddComponent<MeshRenderer>(), material);
        return go;
    }

    // Everything in the lamp is unlit or tiny, so shadows would only cost performance on Quest.
    static void SetupRenderer(MeshRenderer renderer, Material material)
    {
        renderer.sharedMaterial = material;
        renderer.shadowCastingMode = ShadowCastingMode.Off;
        renderer.receiveShadows = false;
    }

    static void EnsureFolder(string name)
    {
        if (!AssetDatabase.IsValidFolder($"{Root}/{name}")) AssetDatabase.CreateFolder(Root, name);
    }
}
